#!/usr/bin/env bash
# ЕДИНЫЙ источник истины flake8-профиля — его зовут и CI (ci.yml), и
# локальная проверка перед пушем. Дублирование команды в двух местах
# уже привело к дрейфу (#589: локально гоняли F,E9 — CI поймал E702).
#
# Style choice: колоночное выравнивание присваиваний/дефолтов —
# E221/E251/E272 игнорируются намеренно; E402 — bootstrap-импорты;
# blank-line правила (E30x) шумны без семантики; F401/F841 ОСТАЮТСЯ —
# ловят реальный dead code.
set -euo pipefail
cd "$(dirname "$0")/../.."
exec python3 -m flake8 src/ tests/ \
  --max-line-length=100 \
  --extend-ignore=E203,W503,E501,E221,E251,E272,E402,E301,E302,E303,E305,E306,E731,E401,E131,E127,E128,E261,E222,E225,E231,E741,F541 \
  --exclude=__pycache__,.venv
